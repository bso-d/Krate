// Mac agent for the identity gate on a VM fixture (TOPOFIX-REVIEW F4, the amended
// rendezvous protocol; TOPOFIX-DESIGN 3.6).
//
// The guest runner (scripts/gate-identity.sh) and this agent share a rendezvous directory in
// the guest. The guest may ask for a row with NOTHING but `{schema, id, row, nonce}`; every
// other field the earlier design carried (args, secrets{file,key}, cert_file, out_dir) is
// owned here by the agent's static row table, generated from this process's own flags. The
// guest's surface shrinks to: ask for one planned row, once, with this run's nonce.
//
// F4 budgets and confinement: at most one request in flight, at most the run plan's row
// count of requests, a wall-clock budget per row, ONE `limactl shell` command per guest file
// read (realpath confined, 64 KiB cap), ONE `limactl copy --backend=scp -r` delivery of the
// response files (M1 observed the flag and the copy both ways), a Mac-held manifest
// (`agent-manifest.tsv`), and a leak scan over the agent's stores for every secret value it
// was given.
//
// The guest is untrusted input everywhere: only the row-table rows, only the fixed argument
// lists, only one request shape, only deliveries under --guest-root. No secret value is ever
// printed: values read from guest files leave this process only through the child's
// environment, and every stored tail is redacted.
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync, chmodSync, statSync } from 'node:fs';
import net from 'node:net';
import { dirname, join, resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));   // scripts/gate/mac
const HELPER_DIR = resolve(HERE, '..');                 // scripts/gate

function die(msg) { console.error(`agent: ${msg}`); process.exit(2); }
function sha256File(f) { return createHash('sha256').update(readFileSync(f)).digest('hex'); }

// ── flags (all fixed by the launcher run-vm-gate.sh) ──
const argvPairs = process.argv.slice(2);
const args = {};
for (let i = 0; i < argvPairs.length; i++) {
  if (!argvPairs[i].startsWith('--')) continue;
  args[argvPairs[i].slice(2)] = argvPairs[i + 1] ?? '';
}
const VM = args.vm || die('--vm NAME is required');
const RDV = args.rendezvous ? resolve(args.rendezvous) : die('--rendezvous DIR is required (the guest directory the runner and this agent share)');
const GUEST_ROOT = args['guest-root'] ? resolve(args['guest-root']) : die('--guest-root is required: the only guest tree this agent may deliver files into');
const PUBLIC_HOST = args['public-host'] || die('--public-host NAME is required');
const PORTS = (args.ports || '443,80').split(',').map((s) => Number(s.trim())).filter((n) => Number.isInteger(n) && n > 0);
const MAC_OUT = args.out ? resolve(args.out) : die('--out DIR is required (the Mac receipt folder this run reports into)');
const PLAN = (args.rows || 'W5,W6').split(',').map((s) => s.trim());
const NONCE = args['rendezvous-nonce'] || die('--rendezvous-nonce is required (generated by the launcher, echoed in every hello and response)');
const GUEST_STATE_DIR = args['guest-state-dir'] || ''; // the fixed 0700 state directory story-row secrets live under; not used by the W rows
const GUEST_CERT_PATH = args['guest-cert'] || die('--guest-cert PATH (the fixed certs/server.crt path in the guest)');
if (net.isIP(PUBLIC_HOST)) die('--public-host must be a DNS name, not an address');
if (!RDV.startsWith(GUEST_ROOT)) die('--rendezvous must sit under --guest-root');
mkdirSync(MAC_OUT, { recursive: true });
const AGENT_LOG = join(MAC_OUT, 'agent.log');
const TMP = process.env.TMPDIR || die('agent: TMPDIR must point inside the run receipt (never /tmp)');
mkdirSync(TMP, { recursive: true });

// ── the row table: generated from this process's own flags; the guest never chooses anything ──
// Every guest request must name a row here; the arguments, secrets and outputs are the
// agent's, not the guest's. spot = the fixed port list the sweep re-probes individually for
// the per-port outcome table (control port 111 plus the guest-side service ports; the
// runner-side derived set decides membership — the probe only reports outcomes).
const ROWS = {
  W5: { script: 'probe.mjs', sub: 'sweep', budgetS: 1500,
        spot: '111,8080,9000,5432,9096,18443,13000,19090,13100,3000,3100,9090' },
  W6: { script: 'probe.mjs', sub: 'clientaddr', budgetS: 240, xff: '203.0.113.9', ua: (id) => `krate-gate-w6-${id}` },
};
// The scripts this agent may execute (scripts/check-identity.py asserts the list; adding a
// script is a deliberate edit here, never a guest decision).
const ALLOWED_SCRIPTS = ['probe.mjs', 'screenshots.mjs', 'screenshots-grafana.mjs', 'screenshots-perses.mjs', 'phase4-browser.mjs'];
for (const r of Object.values(ROWS)) {
  if (!ALLOWED_SCRIPTS.includes(r.script)) die(`agent: row script ${r.script} is not in ALLOWED_SCRIPTS`);
}
const HELLO_INTERVAL_MS = 15000;
const READ_CAP_BYTES = 65536; // one guest command per file read, 64 KiB cap (F4)

function sh(cmd, argv, opts = {}) {
  const r = spawnSync(cmd, argv, { encoding: 'utf8', timeout: opts.timeout || 30000, input: opts.input || '' });
  if (r.error) throw new Error(`${cmd}: ${String(r.error.message || r.error)}`);
  if (r.status !== 0 && !opts.allowFail) throw new Error(`${cmd} ${argv.join(' ')} exited ${r.status}: ${(r.stderr || '').slice(0, 200)}`);
  return { out: r.stdout || '', err: r.stderr || '', status: r.status };
}

// ── guest/Mac facts, M1's exact call shapes (hand-walk 2026-10-17 m1/m1.log) ──
function vmAddr4() {
  const out = sh('limactl', ['shell', VM, '--', 'ip', '-4', '-o', 'addr', 'show']).out;
  const m = /(?:^|\n)\s*\d+:\s*lima0\s+inet\s+(\d+\.\d+\.\d+\.\d+)\//.exec(out);
  if (!m) die('agent: no IPv4 address on the guest lima0 (not a vzNAT VM?): ' + out.slice(0, 200));
  return m[1];
}
function macSrcIp() {
  // The Mac's vmnet address as the guest sees it: the lima0 default-route gateway
  // (M1: `default via 192.168.64.1 dev lima0`; M4's epc-proxy log recorded that same address
  // as the request's remote_addr).
  const out = sh('limactl', ['shell', VM, '--', 'ip', 'route', 'show']).out;
  const m = /default via (\d+\.\d+\.\d+\.\d+) dev lima0/.exec(out);
  if (!m) die('agent: no default route via lima0 in the guest: ' + out.slice(0, 200));
  return m[1];
}
function macIface(vmIp) {
  const out = sh('route', ['-n', 'get', vmIp]).out;
  const m = /interface:\s*(\S+)/.exec(out);
  if (!m) die(`agent: route -n get ${vmIp} names no interface: ` + out.slice(0, 160));
  return m[1]; // M2 observed bridge100
}
function vmGlobal6() {
  const out = sh('limactl', ['shell', VM, '--', 'ip', '-6', 'addr', 'show', 'lima0'], { allowFail: true }).out;
  const m = /inet6\s+([0-9a-fA-F:]+)\/\d+ scope global/.exec(out);
  return m ? m[1] : '';
}
function clockSkewMs() {
  const before = Date.now();
  const guest = Number(sh('limactl', ['shell', VM, '--', 'date', '-u', '+%s']).out.trim());
  const mid = (before + Date.now()) / 2;
  return Math.round(guest * 1000 - mid);
}
function chromeFacts() {
  const bin = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
  if (!existsSync(bin)) die('agent: installed Google Chrome not found at ' + bin);
  const version = sh(bin, ['--version']).out.trim();
  let team = '';
  try {
    const cs = sh('codesign', ['-dv', bin], { allowFail: true });
    team = (/TeamIdentifier=\s*([A-Z0-9]+)/.exec(cs.out + cs.err) || [])[1] || '';
  } catch { team = ''; }
  return { version, team, binary_sha256: sha256File(bin) };
}
function playwrightVersion() {
  const dir = process.env.PW_MODULES || die('agent: PW_MODULES must point at the Mac playwright node_modules (the 1.60.0 pin)');
  const pkg = JSON.parse(readFileSync(join(dir, 'playwright', 'package.json'), 'utf8'));
  if (pkg.version !== '1.60.0') die(`agent: PW_MODULES playwright is ${pkg.version}, expected the gate pin 1.60.0`);
  return pkg.version;
}

// ── hello (design 3.6: the runner's preflight consumes it; rewritten every 15 s) ──
function gateFileDigests() {
  const files = {};
  for (const [base, prefix] of [[HELPER_DIR, 'scripts/gate'], [HERE, 'scripts/gate/mac']]) {
    for (const f of readdirSync(base)) {
      if (f.startsWith('.') || !/\.(py|mjs|sh|json)$/.test(f)) continue;
      const p = join(base, f);
      if (!statSync(p).isFile()) continue;
      files[`${prefix}/${f}`] = sha256File(p);
    }
  }
  return files;
}
let helloSeq = 0;
function writeHello(vmIp, srcIp, iface, g6) {
  const hello = {
    schema: 1, t: new Date().toISOString(), seq: ++helloSeq, pid: process.pid, nonce: NONCE,
    agent_sha256: sha256File(fileURLToPath(import.meta.url)),
    gate_files: gateFileDigests(),
    chrome: { version: CHROME.version, team: CHROME.team, binary_sha256: CHROME.binary_sha256 },
    playwright: playwrightVersion(), node: process.version,
    macos: `${process.platform} ${process.arch}`, headless: false,
    vm: VM, vm_ip: vmIp, mac_src_ip: srcIp, mac_iface: iface,
    clock_skew_ms: clockSkewMs(), vm_g6: g6,   // the guest's lima0 GLOBAL address (fd61:.../64 in M1), not the link-local M4 probed (review S6)
    public_host: PUBLIC_HOST, ports: PORTS, plan: Object.keys(ROWS),
  };
  const tmp = join(RDV, `.hello-${process.pid}.tmp`);
  writeFileSync(tmp, JSON.stringify(hello, null, 2) + '\n');
  renameSync(tmp, join(RDV, 'agent-hello.json'));
  return hello;
}

// ── guest reads: ONE command per read, realpath-confined, size-capped (F4) ──
function guestReadFile(fixedPath, mustBeUnder) {
  if (resolve(fixedPath) !== fixedPath) die(`agent: guest path must be absolute: ${fixedPath}`);
  const guard = mustBeUnder ? `grep -F -- ${JSON.stringify(mustBeUnder)} >/dev/null && cat -- ${JSON.stringify(fixedPath)}` : `cat -- ${JSON.stringify(fixedPath)}`;
  const out = sh('limactl', ['shell', VM, '--', 'sh', '-c',
    `realpath -e -- ${JSON.stringify(fixedPath)} | ${guard}`], { timeout: 20000 });
  const buf = Buffer.from(out.out, 'utf8');
  if (buf.length > READ_CAP_BYTES) die(`agent: guest read of ${fixedPath} exceeds ${READ_CAP_BYTES} bytes`);
  return buf;
}
function guestReadJson(fixedPath) {
  const buf = guestReadFile(fixedPath, GUEST_STATE_DIR);
  try { return JSON.parse(buf.toString('utf8')); } catch (e) { die(`agent: guest file ${fixedPath} is not strict JSON: ${String(e.message || e).slice(0, 120)}`); }
}

// ── secrets: redacted from every stored tail, scanned after the row ──
const SECRETS = []; // values this run has been given; never printed
function addSecret(v) {
  if (typeof v === 'string' && v.length >= 6 && !SECRETS.includes(v)) SECRETS.push(v);
}
function redact(s) {
  let out = String(s || '');
  for (const v of SECRETS) out = out.split(v).join('<redacted>');
  return out;
}
function scanStores() {
  const stores = [AGENT_LOG, join(MAC_OUT, 'agent-manifest.tsv')];
  const hitNames = [];
  for (const f of stores) {
    if (!existsSync(f)) continue;
    const content = readFileSync(f, 'utf8');
    if (SECRETS.some((v) => content.includes(v))) hitNames.push(basename(f));
  }
  return { values: SECRETS.length, hits: hitNames.length, stores: hitNames.concat(stores.map((f) => basename(f))) };
}

// ── delivery back into the guest: ONE limactl copy invocation (M1-observed flag) ──
function deliverToGuest(localDir, guestDir) {
  if (!guestDir.startsWith(GUEST_ROOT)) die(`agent: refusing to deliver outside --guest-root: ${guestDir}`);
  sh('limactl', ['copy', '--backend=scp', '-r', localDir, `${VM}:${guestDir}`], { timeout: 180000 });
}

function runRow(req) {
  const row = ROWS[req.row];
  const sub = row.sub;
  const outDir = join(TMP, `${req.id}-${sub}`);
  mkdirSync(outDir, { recursive: true });
  // The fixture certificate is a fixed guest path owned by this agent's flags; both rows use
  // it (W5's TLS pin and W6's --cacert). One read, once per row, through the single-command
  // read machinery.
  const certLocal = join(TMP, 'gate-cert.pem');
  writeFileSync(certLocal, guestReadFile(GUEST_CERT_PATH, null));
  if (sub === 'sweep') {
    const argv = [join(HERE, row.script), 'sweep', '--ip', STATE.vmIp, '--host', PUBLIC_HOST, '--spot', row.spot,
      '--cert', certLocal, '--port', String(PORTS[0]), '--out', outDir];
    if (STATE.g6 && STATE.iface) argv.push('--v6', `${STATE.g6}%${STATE.iface}`);
    const spawned = spawnSync('node', argv, { encoding: 'utf8', timeout: row.budgetS * 1000, env: { ...process.env, TMPDIR: TMP } });
    const rc = spawned.status === null ? 3 : spawned.status;
    const stdout = (spawned.stdout || '') + (spawned.error ? `\n${String(spawned.error.message || spawned.error)}` : '');
    return { rc, stdout, stderr: spawned.stderr || '', outDir: existsSync(outDir) ? outDir : null };
  }
  if (sub === 'clientaddr') {
    const argv = [join(HERE, row.script), 'clientaddr', '--ip', STATE.vmIp, '--host', PUBLIC_HOST,
      '--port', String(PORTS[0]), '--cert', certLocal, '--ua', row.ua(req.id), '--xff', row.xff, '--out', outDir];   // N7: the row's https port comes from the agent's --ports, not a hardcoded 443
    const spawned = spawnSync('node', argv, { encoding: 'utf8', timeout: row.budgetS * 1000, env: { ...process.env, TMPDIR: TMP } });
    const rc = spawned.status === null ? 3 : spawned.status;
    const stdout = (spawned.stdout || '') + (spawned.error ? `\n${String(spawned.error.message || spawned.error)}` : '');
    return { rc, stdout, stderr: spawned.stderr || '', outDir: existsSync(outDir) ? outDir : null };
  }
  die(`agent: row ${req.row} maps to unmapped sub ${sub}`);
}

// ── manifest (Mac-held, F4) ──
const manifestRows = [];
function appendManifest(m) {
  manifestRows.push(m);
  const tsv = ['request_id\trow\trequest_sha256\tfiles(chromium only)\tchrome_version']
    .concat(manifestRows.map((x) => [x.id, x.row, x.request_sha256, x.files.join(' '), CHROME.version].join('\t'))).join('\n');
  const f = join(MAC_OUT, 'agent-manifest.tsv');
  writeFileSync(f, tsv + '\n');
  chmodSync(f, 0o644);
  return sha256File(f);
}

// ── request claim: the guest may say exactly {schema,id,row,nonce} ──
const seenRequests = new Set();
let inFlight = false;
function claimRequest(file) {
  const claimed = file.replace(/\.json$/, '.processing');
  try { renameSync(join(RDV, file), claimed); } catch { return null; }
  let parsed;
  try { parsed = JSON.parse(readFileSync(claimed, 'utf8')); } catch (e) {
    const bad = `refused: unparseable request ${file}: ${String(e.message || e).slice(0, 80)}`;
    rmSync(claimed);
    return { bad };
  }
  const keys = Object.keys(parsed).sort().join(',');
  if (keys !== 'id,nonce,row,schema') {
    rmSync(claimed);
    return { bad: `refused: the guest request carries [${keys}]; the protocol is exactly {schema,id,row,nonce} (F4)` };
  }
  if (parsed.schema !== 1 || parsed.nonce !== NONCE) {
    rmSync(claimed);
    return { bad: 'refused: schema or rendezvous nonce mismatch' };
  }
  if (!ROWS[parsed.row]) {
    rmSync(claimed);
    return { bad: `refused: row ${JSON.stringify(String(parsed.row))} is not in this run's plan: ${Object.keys(ROWS).join(', ')}` };
  }
  if (seenRequests.has(parsed.id)) {
    rmSync(claimed);
    return { bad: `refused: request id ${JSON.stringify(String(parsed.id))} was already served` };
  }
  if (inFlight) {
    try { renameSync(claimed, join(RDV, file)); } catch { /* keep the claimed name; the next poll retries */ }
    return null;
  }
  if (manifestRows.length >= PLAN.length) {
    rmSync(claimed);
    return { bad: 'refused: the run plan allows no more requests (at most one request per planned row, F4)' };
  }
  return { req: parsed, claimedPath: claimed };
}
function execute(claim) {
  const { req, claimedPath } = claim;
  inFlight = true;
  seenRequests.add(req.id);
  const t0 = new Date().toISOString();
  let res = { rc: 3, stdout: '', stderr: '', outDir: null };
  try { res = runRow(req); } catch (e) { res = { rc: 3, stdout: 'agent error: ' + String(e.message || e), stderr: '', outDir: null }; }
  const tEnd = new Date().toISOString();
  const files = [];
  let browserJsonSha = '';
  if (res.outDir) {
    for (const f of readdirSync(res.outDir)) {
      const p = join(res.outDir, f);
      if (!statSync(p).isFile()) continue;
      files.push({ name: f, sha256: sha256File(p), bytes: statSync(p).size });
      if (f === 'browser.json') browserJsonSha = sha256File(p);
    }
    try { deliverToGuest(res.outDir, join(GUEST_ROOT, 'agent-out', req.row.toLowerCase())); } catch (e) {
      console.log(`agent: delivery failed: ${String(e.message || e).slice(0, 160)}`);
      if (res.rc === 0) res.rc = 4;
    }
  } else {
    console.log(`agent: no evidence directory produced for ${req.row} (exit ${res.rc})`);
  }
  const stdoutTail = redact((res.stdout + '\n' + (res.stderr || '')).slice(-8192));
  const manifestSha = appendManifest({
    id: req.id, row: req.row,
    request_sha256: createHash('sha256').update(JSON.stringify(req)).digest('hex'),
    files: files.filter((f) => f.name.endsWith('.png') || f.name.endsWith('.json') || f.name.endsWith('.tsv')).map((f) => f.sha256.slice(0, 12)),
  });
  const resp = {
    schema: 1, id: req.id, row: req.row, nonce: NONCE,
    exit: res.rc, stdout_tail: stdoutTail,
    files, browser_json_sha256: browserJsonSha,
    mac_leak_scan: scanStores(),
    agent_manifest: manifestSha.slice(0, 12),
    t_start: t0, t_end: tEnd,
  };
  const tmp = join(RDV, `.resp-${req.id}-${process.pid}.tmp`);
  writeFileSync(tmp, JSON.stringify(resp, null, 2) + '\n');
  renameSync(tmp, join(RDV, `resp-${req.id}.json`));
  rmSync(claimedPath);
  inFlight = false;
  return resp;
}

// ── main ──
const STATE = { vmIp: vmAddr4() };
const srcIp = macSrcIp();
if (srcIp === STATE.vmIp) die('agent: the lima0 gateway equals the guest address');
const iface = macIface(STATE.vmIp);
const g6 = vmGlobal6();
STATE.iface = iface;
STATE.g6 = g6;
const CHROME = chromeFacts();
writeHello(STATE.vmIp, srcIp, iface, g6);
console.log(`agent: ready vm=${VM} vm_ip=${STATE.vmIp} mac_src_ip=${srcIp} iface=${iface} g6=${g6 || 'none'} plan=${Object.keys(ROWS).join(',')} nonce=bound`); // the nonce value is never printed (review N6)
// The heartbeat keeps the process alive until the launcher stops it; the poll loop is unref'd
// so an idle teardown does not hang on it.
setInterval(() => writeHello(STATE.vmIp, srcIp, iface, g6), HELLO_INTERVAL_MS);
const poll = setInterval(() => {
  if (inFlight) return;
  let files;
  try { files = readdirSync(RDV); } catch (e) { console.error('agent: rendezvous unreadable: ' + String(e.message || e)); return; }
  for (const f of files.filter((x) => /^req-[0-9]{4}\.json$/.test(x)).sort()) {
    const claim = claimRequest(f);
    if (claim === null) continue;
    if (claim.bad) { console.log('agent: ' + claim.bad); continue; }
    const resp = execute(claim);
    console.log(`agent: ${resp.row} req=${resp.id} exit=${resp.exit} files=${resp.files.length} manifest=${resp.agent_manifest}`);
    break; // at most one request in flight (F4)
  }
}, 1000);
poll.unref();
process.on('SIGINT', () => process.exit(130));
process.on('SIGTERM', () => process.exit(143));