const HELLO_INTERVAL_MS = 15000;
const POLL_INTERVAL_MS = 3000;   // TOPOFIX-DESIGN 3.6: each poll is one `limactl shell` round trip into the guest
const READ_CAP_BYTES = 65536; // one guest command per file read, 64 KiB cap (F4)

function sh(cmd, argv, opts = {}) {
  const r = spawnSync(cmd, argv, { encoding: 'utf8', timeout: opts.timeout || 30000, input: opts.input || '' });
  if (r.error) throw new Error(`${cmd}: ${String(r.error.message || r.error)}`);
  if (r.status !== 0 && !opts.allowFail) throw new Error(`${cmd} ${argv.join(' ')} exited ${r.status}: ${(r.stderr || '').slice(0, 200)}`);
  return { out: r.stdout || '', err: r.stderr || '', status: r.status };
}

// ── guest/Mac facts, M1's exact call shapes (hand-walk 2026-10-17 m1/m1.log) ──
function vmAddr4() {
  const out = sh('limactl', ['shell', VM, '--', 'ip', '-4', '-o', 'addr', 'show']).out;
  const m = /(?:^|\n)\s*\d+:\s*lima0\s+inet\s+(\d+\.\d+\.\d+\.\d+)\//.exec(out);
  if (!m) die('agent: no IPv4 address on the guest lima0 (not a vzNAT VM?): ' + clip(out, 200));
  return m[1];
}
function macSrcIp() {
  // The Mac's vmnet address as the guest sees it: the lima0 default-route gateway
  // (M1: `default via 192.168.64.1 dev lima0`; M4's epc-proxy log recorded that same address
  // as the request's remote_addr).
  const out = sh('limactl', ['shell', VM, '--', 'ip', 'route', 'show']).out;
  const m = /default via (\d+\.\d+\.\d+\.\d+) dev lima0/.exec(out);
  if (!m) die('agent: no default route via lima0 in the guest: ' + clip(out, 200));
  return m[1];
}
function macIface(vmIp) {
  const out = sh('route', ['-n', 'get', vmIp]).out;
  const m = /interface:\s*(\S+)/.exec(out);
  if (!m) die(`agent: route -n get ${vmIp} names no interface: ` + clip(out, 160));
  return m[1]; // M2 observed bridge100
}
// The IPv6 target handed to probe.mjs: a global address is routed without a zone (a `%iface` suffix on a
// non-link-local address may read as no-route-or-scope and make the pass vacuous, TOPOFIX2 PRE-6); only an
// fe80::/10 address needs the Mac interface as its zone.
function v6Target(addr, iface) { return /^fe[89ab][0-9a-f]:/i.test(addr) && iface ? `${addr}%${iface}` : addr; }
function vmGlobal6() {
  const out = sh('limactl', ['shell', VM, '--', 'ip', '-6', 'addr', 'show', 'lima0'], { allowFail: true }).out;
  const m = /inet6\s+([0-9a-fA-F:]+)\/\d+ scope global/.exec(out);
  return m ? m[1] : '';
}
function clockSkewMs() {
  const before = Date.now();
  const guest = Number(sh('limactl', ['shell', VM, '--', 'date', '-u', '+%s']).out.trim());
  const mid = (before + Date.now()) / 2;
  return Math.round(guest * 1000 - mid);
}
function chromeFacts() {
  const bin = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
  if (!existsSync(bin)) die('agent: installed Google Chrome not found at ' + bin);
  const version = sh(bin, ['--version']).out.trim();
  let team = '';
  try {
    const cs = sh('codesign', ['-dv', bin], { allowFail: true });
    team = (/TeamIdentifier=\s*([A-Z0-9]+)/.exec(cs.out + cs.err) || [])[1] || '';
  } catch { team = ''; }
  return { version, team, binary_sha256: sha256File(bin) };
}
function playwrightVersion() {
  const dir = process.env.PW_MODULES || die('agent: PW_MODULES must point at the Mac playwright node_modules (the 1.60.0 pin)');
  const pkg = JSON.parse(readFileSync(join(dir, 'playwright', 'package.json'), 'utf8'));
  if (pkg.version !== '1.60.0') die(`agent: PW_MODULES playwright is ${pkg.version}, expected the gate pin 1.60.0`);
  return pkg.version;
}

// ── hello (design 3.6: the runner's preflight consumes it; rewritten every 15 s) ──
function gateFileDigests() {
  const files = {};
  for (const [base, prefix] of [[HELPER_DIR, 'scripts/gate'], [HERE, 'scripts/gate/mac']]) {
    for (const f of readdirSync(base)) {
      if (f.startsWith('.') || !/\.(py|mjs|sh|json)$/.test(f)) continue;
      const p = join(base, f);
      if (!statSync(p).isFile()) continue;
      files[`${prefix}/${f}`] = sha256File(p);
    }
  }
  return files;
}
let helloSeq = 0;
function writeHello(vmIp, srcIp, iface, g6) {
  const hello = {
    schema: 1, t: new Date().toISOString(), seq: ++helloSeq, pid: process.pid, nonce: NONCE,
    agent_sha256: sha256File(fileURLToPath(import.meta.url)),
    gate_files: gateFileDigests(),
    chrome: { version: CHROME.version, team: CHROME.team, binary_sha256: CHROME.binary_sha256 },
    playwright: playwrightVersion(), node: process.version,
    macos: `${process.platform} ${process.arch}`, headless: false,
    vm: VM, vm_ip: vmIp, mac_src_ip: srcIp, mac_iface: iface,
    clock_skew_ms: clockSkewMs(), vm_g6: g6,   // the guest's lima0 GLOBAL address (fd61:.../64 in M1), not the link-local M4 probed (review S6)
    public_host: PUBLIC_HOST, ports: PORTS, plan: PLAN,
  };
  guestPut('agent-hello.json', JSON.stringify(hello, null, 2) + '\n');
  return hello;
}

// ── guest operations (TOPOFIX2 PRE-0): the rendezvous is a GUEST directory, so every operation
// on it is ONE `limactl shell VM -- sh -c <script>` call carrying only validated paths, each in
// single quotes (q), or a `limactl copy --backend=scp` plus one guest `mv -f` (guestPut) ──
function guestSh(script, opts = {}) {
  return sh('limactl', ['shell', VM, '--', 'sh', '-c', script], { timeout: opts.timeout || 30000, allowFail: opts.allowFail });
}
// list: the request names the guest holds (`ls -1A`); nothing else in the directory is looked at
function guestListRequests() {
  return guestSh(`ls -1A -- ${q(RDV)}`).out.split('\n').filter((x) => /^req-[0-9]{4}\.json$/.test(x)).sort();
}
// put (hello and response): a 0600 file under TMP (the receipt TMPDIR), copied into a dot-temp
// inside RDV, renamed by one guest `mv -f` (atomic inside RDV), the local file deleted after
function guestPut(name, text) {
  if (!/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(name)) die(`refusing to put a file named ${JSON.stringify(name)} into the rendezvous`);
  const local = join(TMP, `.put-${process.pid}-${name}`);
  const guestTmp = `${RDV}/.${name}.${process.pid}.tmp`;
  writeFileSync(local, text, { mode: 0o600 });
  chmodSync(local, 0o600);
  try {
    sh('limactl', ['copy', '--backend=scp', local, `${VM}:${guestTmp}`], { timeout: 60000 });
    guestSh(`mv -f -- ${q(guestTmp)} ${q(`${RDV}/${name}`)}`);
  } finally {
    rmSync(local, { force: true });
  }
}
// remove a claimed request (after its response, or when it is refused); a failure is only logged
function dropClaimed(claimedPath) {
  try { guestSh(`rm -f -- ${q(claimedPath)}`); } catch (e) { console.error('agent: could not remove ' + claimedPath + ': ' + clip(e.message || e, 120)); }
}

// ── guest reads: ONE command per read, realpath-confined, size-capped (F4) ──
// Review R5: the confinement is a prefix test on whole path components of the RESOLVED paths (`"$d"/*`), and the file read is the resolved one.
// A substring match (`grep -F`) also accepted `<dir>-other/...` and refused every read when the directory itself had a symlinked component.
function guestReadFile(fixedPath, mustBeUnder) {
  const script = mustBeUnder
    ? `r="$(realpath -e -- ${q(fixedPath)})" && d="$(realpath -e -- ${q(mustBeUnder)})" && case "$r" in "$d"/*) cat -- "$r" ;; esac`
    : `cat -- ${q(fixedPath)}`;
  const out = guestSh(script, { timeout: 20000 });
  const buf = Buffer.from(out.out, 'utf8');
  if (buf.length > READ_CAP_BYTES) throw new Error(`guest read of ${fixedPath} exceeds ${READ_CAP_BYTES} bytes`);
  return buf;
}
// the request reader: the guest file must resolve under the explicit directory; strict JSON.parse
// (a bad file throws, the claim turns that into a refusal; the guest must not be able to stop the agent)
function guestReadJson(fixedPath, mustBeUnder) {
  return JSON.parse(guestReadFile(fixedPath, mustBeUnder).toString('utf8'));
}

// ── leak scan: redacted from every stored tail, scanned after the row ──
// No W row carries a secret value: a guest request is {schema,id,row,nonce} and the rows take
// only flags, so this list is empty on purpose. redact() and scanStores() stay so that the
// response's mac_leak_scan reports `values: 0` honestly; a story row that hands the agent a
// secret must register its values here first.
const SECRETS = [];
function redact(s) {
  let out = String(s || '');
  for (const v of SECRETS) out = out.split(v).join('<redacted>');
  return out;
}
function scanStores() {
  const stores = [AGENT_LOG, join(MAC_OUT, 'agent-manifest.tsv')];
  const hitNames = [];
  for (const f of stores) {
    if (!existsSync(f)) continue;
    const content = readFileSync(f, 'utf8');
    if (SECRETS.some((v) => content.includes(v))) hitNames.push(basename(f));
  }
  return { values: SECRETS.length, hits: hitNames.length, stores: hitNames.concat(stores.map((f) => basename(f))) };
}

// ── delivery back into the guest: ONE limactl copy invocation (M1-observed flag) ──
function deliverToGuest(localDir, guestDir) {
  if (!guestDir.startsWith(GUEST_ROOT + '/')) die(`agent: refusing to deliver outside --guest-root: ${guestDir}`);
  sh('limactl', ['copy', '--backend=scp', '-r', localDir, `${VM}:${guestPath('delivery target', guestDir)}`], { timeout: 180000 });
}

function runRow(req) {
  const row = ROWS[req.row];
  const sub = row.sub;
  const outDir = join(TMP, `${req.id}-${sub}`);
  mkdirSync(outDir, { recursive: true });
  // The fixture certificate is a fixed guest path owned by this agent's flags; both rows use
  // it (W5's TLS pin and W6's --cacert). One read, once per row, through the single-command
  // read machinery.
  const certLocal = join(TMP, 'gate-cert.pem');
  writeFileSync(certLocal, guestReadFile(GUEST_CERT_PATH, null));
  if (sub === 'sweep') {
    const argv = [join(HERE, row.script), 'sweep', '--ip', STATE.vmIp, '--host', PUBLIC_HOST, '--spot', row.spot,
      '--cert', certLocal, '--port', String(PORTS[0]), '--out', outDir];
    if (STATE.g6) argv.push('--v6', v6Target(STATE.g6, STATE.iface));
    const spawned = spawnSync('node', argv, { encoding: 'utf8', timeout: row.budgetS * 1000, env: { ...process.env, TMPDIR: TMP } });
    const rc = spawned.status === null ? 3 : spawned.status;
    const stdout = (spawned.stdout || '') + (spawned.error ? `\n${String(spawned.error.message || spawned.error)}` : '');
    return { rc, stdout, stderr: spawned.stderr || '', outDir: existsSync(outDir) ? outDir : null };
  }
  if (sub === 'clientaddr') {
    const argv = [join(HERE, row.script), 'clientaddr', '--ip', STATE.vmIp, '--host', PUBLIC_HOST,
      '--port', String(PORTS[0]), '--cert', certLocal, '--ua', row.ua(req.id), '--xff', row.xff, '--out', outDir];   // N7: the row's https port comes from the agent's --ports, not a hardcoded 443
    const spawned = spawnSync('node', argv, { encoding: 'utf8', timeout: row.budgetS * 1000, env: { ...process.env, TMPDIR: TMP } });
    const rc = spawned.status === null ? 3 : spawned.status;
    const stdout = (spawned.stdout || '') + (spawned.error ? `\n${String(spawned.error.message || spawned.error)}` : '');
    return { rc, stdout, stderr: spawned.stderr || '', outDir: existsSync(outDir) ? outDir : null };
  }
  die(`agent: row ${req.row} maps to unmapped sub ${sub}`);
}

// ── manifest (Mac-held, F4) ──
const manifestRows = [];
function appendManifest(m) {
  manifestRows.push(m);
  const tsv = ['request_id\trow\trequest_sha256\tfiles(chromium only)\tchrome_version']
    .concat(manifestRows.map((x) => [x.id, x.row, x.request_sha256, x.files.join(' '), CHROME.version].join('\t'))).join('\n');
  const f = join(MAC_OUT, 'agent-manifest.tsv');
  writeFileSync(f, tsv + '\n');
  chmodSync(f, 0o644);
  return sha256File(f);
}

// ── request claim: the guest may say exactly {schema,id,row,nonce} ──
const seenRequests = new Set();
const servedRows = new Set();   // review T18: one request per planned row, whatever id it comes under
let inFlight = false;
function claimRequest(file) {
  const src = `${RDV}/${file}`;
  const claimed = `${src}.claimed-${process.pid}`;
  // claim = ONE guest mv; a non-zero rc (the file vanished, or another claimant) means: skip it this poll
  if (guestSh(`mv -- ${q(src)} ${q(claimed)}`, { allowFail: true }).status !== 0) return null;
  let parsed;
  try { parsed = guestReadJson(claimed, RDV); } catch (e) {
    dropClaimed(claimed);
    return { bad: `refused: unreadable or unparseable request ${file}: ${clip(e.message || e, 80)}` };
  }
  if (parsed === null || typeof parsed !== 'object') {
    dropClaimed(claimed);
    return { bad: `refused: request ${file} is not a JSON object` };
  }
  const keys = Object.keys(parsed).sort().join(',');
  if (keys !== 'id,nonce,row,schema') {
    dropClaimed(claimed);
    return { bad: `refused: the guest request carries the keys ${clip(keys)}; the protocol is exactly {schema,id,row,nonce} (F4)` };
  }
  if (parsed.schema !== 1 || parsed.nonce !== NONCE) {
    dropClaimed(claimed);
    return { bad: 'refused: schema or rendezvous nonce mismatch' };
  }
  // the id names the response file (resp-<4 digits>.json) and the row's scratch folder: only a small integer may do that, and
  // (review T11) it must be the id of the file the request came in (req-<4 digits>.json), checked before any path uses it
  if (!Number.isInteger(parsed.id) || parsed.id < 1 || parsed.id > 9999) {
    dropClaimed(claimed);
    return { bad: 'refused: the request id must be an integer from 1 to 9999 (it names resp-<4 digits>.json)' };
  }
  if (parsed.id !== Number(file.slice(4, 8))) {
    dropClaimed(claimed);
    return { bad: `refused: the request id ${parsed.id} is not the id of its file ${file}` };
  }
  if (typeof parsed.row !== 'string' || !PLAN.includes(parsed.row)) {
    dropClaimed(claimed);
    return { bad: `refused: row ${clip(parsed.row)} is not in this run's plan: ${PLAN.join(', ')}` };
  }
  if (servedRows.has(parsed.row)) {
    dropClaimed(claimed);
    return { bad: `refused: row ${parsed.row} was already served (one request per planned row)` };
  }
  if (seenRequests.has(parsed.id)) {
    dropClaimed(claimed);
    return { bad: `refused: request id ${JSON.stringify(String(parsed.id))} was already served` };
  }
  if (inFlight) {
    try { guestSh(`mv -- ${q(claimed)} ${q(src)}`, { allowFail: true }); } catch { /* keep the claimed name; the next poll retries */ }
    return null;
  }
  if (manifestRows.length >= PLAN.length) {
    dropClaimed(claimed);
    return { bad: 'refused: the run plan allows no more requests (at most one request per planned row, F4)' };
  }
  return { req: parsed, claimedPath: claimed };
}
function execute(claim) {
  const { req, claimedPath } = claim;
  inFlight = true;
  seenRequests.add(req.id);
  servedRows.add(req.row);
  const t0 = new Date().toISOString();
  let res = { rc: 3, stdout: '', stderr: '', outDir: null };
  try { res = runRow(req); } catch (e) { res = { rc: 3, stdout: 'agent error: ' + String(e.message || e), stderr: '', outDir: null }; }
  const tEnd = new Date().toISOString();
  const files = [];
  let browserJsonSha = '';
  if (res.outDir) {
    for (const f of readdirSync(res.outDir)) {
      const p = join(res.outDir, f);
      if (!statSync(p).isFile()) continue;
      files.push({ name: f, sha256: sha256File(p), bytes: statSync(p).size });
      if (f === 'browser.json') browserJsonSha = sha256File(p);
    }
    try { deliverToGuest(res.outDir, join(GUEST_ROOT, 'agent-out', req.row.toLowerCase())); } catch (e) {
      console.log(`agent: delivery failed: ${clip(e.message || e, 160)}`);
      if (res.rc === 0) res.rc = 4;
    }
  } else {
    console.log(`agent: no evidence directory produced for ${req.row} (exit ${res.rc})`);
  }
  const stdoutTail = redact((res.stdout + '\n' + (res.stderr || '')).slice(-8192));
  const manifestSha = appendManifest({
    id: req.id, row: req.row,
    request_sha256: createHash('sha256').update(JSON.stringify(req)).digest('hex'),
    files: files.filter((f) => f.name.endsWith('.png') || f.name.endsWith('.json') || f.name.endsWith('.tsv')).map((f) => f.sha256.slice(0, 12)),
  });
  const resp = {
    schema: 1, id: req.id, row: req.row, nonce: NONCE,
    exit: res.rc, stdout_tail: stdoutTail,
    files, browser_json_sha256: browserJsonSha,
    mac_leak_scan: scanStores(),
    agent_manifest: manifestSha.slice(0, 12),
    t_start: t0, t_end: tEnd,
  };
  guestPut(`resp-${String(req.id).padStart(4, '0')}.json`, JSON.stringify(resp, null, 2) + '\n');   // the requester waits for resp-<4 digits>.json (PRE-1)
  dropClaimed(claimedPath);
  inFlight = false;
  return resp;
}

